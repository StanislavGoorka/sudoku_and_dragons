create table public.daily_runs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  day date not null,
  difficulty text not null check (difficulty in ('easy', 'medium', 'hard')),
  seed bigint not null check (seed between 0 and 4294967295),
  started_at timestamptz not null default clock_timestamp(),
  elapsed_ms bigint check (elapsed_ms between 1 and 86400000),
  errors integer check (errors between 0 and 1000)
);
create index daily_runs_ranking on public.daily_runs(day, difficulty, elapsed_ms, user_id) where elapsed_ms is not null;
create index daily_runs_owner_day on public.daily_runs(user_id, day);
alter table public.daily_runs enable row level security;
revoke all on public.daily_runs from public, anon, authenticated;
grant select on public.daily_runs to authenticated;
grant all on public.daily_runs to service_role;
create policy "Players read their own daily runs" on public.daily_runs for select to authenticated
  using ((select auth.uid()) = user_id);

-- The trusted referee supplies the common seed and validates the replay. Players cannot start or
-- finish a run through SQL themselves. Both timestamps are generated by the database.
create function public.begin_daily_run(player uuid, day_key date, level text, board_seed bigint)
returns jsonb language plpgsql security invoker set search_path = '' as $$
declare made public.daily_runs;
begin
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(player::text, 6106));
  if day_key <> (pg_catalog.clock_timestamp() at time zone 'UTC')::date then raise exception 'day-changed'; end if;
  if (select count(*) from public.daily_runs where user_id = player and day = day_key) >= 20 then
    raise exception 'daily-limit';
  end if;
  insert into public.daily_runs(user_id, day, difficulty, seed) values (player, day_key, level, board_seed) returning * into made;
  return pg_catalog.to_jsonb(made);
end;
$$;
create function public.finish_daily_run(player uuid, run_id uuid, mistakes integer)
returns jsonb language plpgsql security invoker set search_path = '' as $$
declare played public.daily_runs; elapsed bigint;
begin
  select * into played from public.daily_runs where id = run_id and user_id = player for update;
  if not found then raise exception 'not-found'; end if;
  if played.elapsed_ms is null then
    elapsed := greatest(1, floor(extract(epoch from (pg_catalog.clock_timestamp() - played.started_at)) * 1000));
    if elapsed > 86400000 then raise exception 'expired'; end if;
    update public.daily_runs set elapsed_ms = elapsed, errors = mistakes where id = run_id returning * into played;
  end if;
  return pg_catalog.jsonb_build_object('elapsed_ms', played.elapsed_ms, 'day', played.day, 'difficulty', played.difficulty);
end;
$$;
revoke execute on function public.begin_daily_run(uuid,date,text,bigint), public.finish_daily_run(uuid,uuid,integer) from public, anon, authenticated;
grant execute on function public.begin_daily_run(uuid,date,text,bigint), public.finish_daily_run(uuid,uuid,integer) to service_role;

create function private.daily_leaderboard(level text, day_key date default (now() at time zone 'UTC')::date)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare result jsonb;
begin
  if auth.uid() is null then raise exception 'not-signed-in' using errcode = '42501'; end if;
  if level not in ('easy','medium','hard') or day_key is null or day_key > (now() at time zone 'UTC')::date or
    day_key < (now() at time zone 'UTC')::date - 7 then raise exception 'bad-category'; end if;
  with best as (
    select distinct on (r.user_id) r.user_id, r.elapsed_ms from public.daily_runs r
    where r.day = day_key and r.difficulty = level and r.elapsed_ms is not null
    order by r.user_id, r.elapsed_ms
  ), ranked as (
    select b.user_id, b.elapsed_ms, coalesce(p.nickname, 'Gracz') as nickname,
      rank() over (order by b.elapsed_ms) as place, b.user_id = auth.uid() as mine
    from best b left join public.profiles p on p.id = b.user_id
  )
  select pg_catalog.jsonb_build_object('day', day_key, 'difficulty', level,
    'top', coalesce((select pg_catalog.jsonb_agg(pg_catalog.to_jsonb(t)) from
      (select place, nickname, elapsed_ms, mine from ranked order by place, nickname, user_id limit 5) t), '[]'::jsonb),
    'own', (select pg_catalog.jsonb_build_object('place', place, 'elapsed_ms', elapsed_ms) from ranked where mine),
    'players', (select count(*) from ranked)) into result;
  return result;
end;
$$;
revoke execute on function private.daily_leaderboard(text,date) from public, anon;
grant usage on schema private to authenticated;
grant execute on function private.daily_leaderboard(text,date) to authenticated;
create function public.daily_leaderboard(level text, day_key date default (now() at time zone 'UTC')::date)
returns jsonb language sql security invoker set search_path = '' as $$ select private.daily_leaderboard(level, day_key); $$;
revoke execute on function public.daily_leaderboard(text,date) from public, anon;
grant execute on function public.daily_leaderboard(text,date) to authenticated;
