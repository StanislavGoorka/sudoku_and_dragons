// Renders the app icon from assets/src/icon-background.svg and icon-foreground.svg.
// Both are drawn on the full 108 dp adaptive-icon canvas (1024 px); launchers show only the middle
// 72 dp, cut to a circle or squircle, so the artwork stays near the centre.
//
// Writes:
//   android/app/src/main/res/mipmap-*/ic_launcher_{foreground,background}.png  adaptive layers (108 dp)
//   android/app/src/main/res/mipmap-*/ic_launcher{,_round}.png                 legacy icons (48 dp, Android 7)
//   android/app/src/main/res/mipmap-anydpi-v26/ic_launcher{,_round}.xml       adaptive icon definitions
//   assets/icon-1024.png, assets/icon-512.png   flat square of the visible area (App Store, Google Play)
// Usage: node scripts/render-icons.ts [--preview out.png]   (npm run icons)
import { mkdir, writeFile } from 'node:fs/promises';
import sharp from 'sharp';

const SRC = 'assets/src';
const RES = 'android/app/src/main/res';
const CANVAS = 1024;
const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
/** The visible 72 dp out of the 108 dp canvas. */
const VISIBLE = 72 / 108;

/** Rasterises an SVG source at `size` px straight from the vector, so every size is sharp. */
function layer(file: string, size: number): sharp.Sharp {
  return sharp(`${SRC}/${file}`, { density: (72 * size) / CANVAS }).resize(size, size);
}

/** Both layers flattened, at `size` px for the whole canvas. */
async function flat(size: number): Promise<Buffer> {
  const foreground = await layer('icon-foreground.svg', size).png().toBuffer();
  return layer('icon-background.svg', size).composite([{ input: foreground }]).png().toBuffer();
}

/** The visible middle of the icon as a `size` px square, optionally cut to rounded corners. */
async function visible(size: number, cornerRadius = 0): Promise<Buffer> {
  const full = Math.round(size / VISIBLE);
  const offset = Math.round((full - size) / 2);
  const square = await sharp(await flat(full))
    .extract({ left: offset, top: offset, width: size, height: size })
    .png()
    .toBuffer();
  if (!cornerRadius) return square;
  const mask = Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}">` +
      `<rect width="${size}" height="${size}" rx="${cornerRadius}" fill="#fff"/></svg>`,
  );
  return sharp(square).composite([{ input: mask, blend: 'dest-in' }]).png().toBuffer();
}

const ADAPTIVE_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/render-icons.ts -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
`;

for (const [name, scale] of Object.entries(DENSITIES)) {
  const dir = `${RES}/mipmap-${name}`;
  await mkdir(dir, { recursive: true });
  const layerSize = Math.round(108 * scale);
  await layer('icon-foreground.svg', layerSize).png().toFile(`${dir}/ic_launcher_foreground.png`);
  await layer('icon-background.svg', layerSize).png().toFile(`${dir}/ic_launcher_background.png`);
  const legacySize = Math.round(48 * scale);
  await writeFile(`${dir}/ic_launcher.png`, await visible(legacySize, legacySize * 0.18));
  await writeFile(`${dir}/ic_launcher_round.png`, await visible(legacySize, legacySize / 2));
}
await mkdir(`${RES}/mipmap-anydpi-v26`, { recursive: true });
await writeFile(`${RES}/mipmap-anydpi-v26/ic_launcher.xml`, ADAPTIVE_XML);
await writeFile(`${RES}/mipmap-anydpi-v26/ic_launcher_round.xml`, ADAPTIVE_XML);

// Stores want a full square; they apply their own rounding.
await writeFile('assets/icon-1024.png', await visible(1024));
await writeFile('assets/icon-512.png', await visible(512));
console.log('Icons written to android/app/src/main/res/mipmap-* and assets/icon-{1024,512}.png');

const previewIndex = process.argv.indexOf('--preview');
if (previewIndex > 0) await writePreview(process.argv[previewIndex + 1] ?? 'icon-preview.png');

/** A sheet of the icon under launcher masks (circle, squircle, square) at 192, 96 and 48 px. */
async function writePreview(file: string): Promise<void> {
  const radii = [0.5, 0.3, 0.08];
  const sizes = [192, 96, 48];
  const cell = 220;
  const tiles = [];
  for (const [row, radius] of radii.entries()) {
    for (const [col, size] of sizes.entries()) {
      tiles.push({
        input: await visible(size, size * radius),
        left: col * cell + Math.round((cell - size) / 2),
        top: row * cell + Math.round((cell - size) / 2),
      });
    }
  }
  await sharp({
    create: { width: cell * sizes.length, height: cell * radii.length, channels: 4, background: '#e9e6ef' },
  })
    .composite(tiles)
    .png()
    .toFile(file);
  console.log(`Preview written to ${file}`);
}
